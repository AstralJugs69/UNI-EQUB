function parseArgs() {
  const args = process.argv.slice(2);
  const parsed = {};
  for (let index = 0; index < args.length; index += 1) {
    if (args[index] === '--output') {
      parsed.output = args[index + 1];
      index += 1;
    }
  }
  return parsed;
}

function read(relativePath) {
  const filePath = path.join(repoRoot, relativePath);
  if (!fs.existsSync(filePath)) {
    throw new Error(`Missing required demo file: ${relativePath}`);
  }
  return fs.readFileSync(filePath, 'utf8');
}

function assertIncludes(content, token, label) {
  if (!content.includes(token)) {
    throw new Error(`Missing ${label}: ${token}`);
  }
}

function main() {
  const args = parseArgs();

  for (const file of requiredFiles) {
    read(file);
  }

  const demo = read('Build/delivery/demo/phase2_completed_features_demo.md');
  const checklist = read('Build/delivery/demo/phase2_demo_operator_checklist.md');
  const config = read('supabase/config.toml');

  requiredDemoTokens.forEach(token => assertIncludes(demo, token, 'demo runbook token'));
  requiredChecklistTokens.forEach(token => assertIncludes(checklist, token, 'operator checklist token'));
  assertIncludes(config, '[functions.default-maintenance]', 'default-maintenance function config');

  const result = {
    scenario: 'phase2-demo-readiness-validation',
    demoFiles: {
      runbook: 'Build/delivery/demo/phase2_completed_features_demo.md',
      operatorChecklist: 'Build/delivery/demo/phase2_demo_operator_checklist.md',
    },
    completedChecks: [
      'demo runbook exists with live and evidence-backed modes',
      'in-app demo mode and validation script are documented',
      'operator checklist exists with setup, commands, accounts, and what-not-to-claim guardrails',
      'completed Phase 2 evidence files referenced by the demo are present',
      'seeded final-draw script and USSD harness are present for live/demo shortcuts',
      'default-maintenance Edge Function is registered in Supabase config',
    ],
    limitations: [
      'live demo still requires deployed Edge Functions, valid Supabase secrets, OTP-capable phone, and device/emulator access',
      'screenshots/videos are not generated by this validation script',
    ],
    requiresSupabaseCredentials: false,
    validatedAt: new Date().toISOString(),
  };

  const output = JSON.stringify(result, null, 2);
  if (args.output) {
    const outputPath = path.resolve(repoRoot, args.output);
    fs.mkdirSync(path.dirname(outputPath), { recursive: true });
    fs.writeFileSync(outputPath, `${output}\n`);
  }
  console.log(output);
}

main();
